import { BadgeCheck, Bot } from 'lucide-react'
import type { FinalReport, Run } from '@/domain/run'
import { formatDuration, formatUsd } from '../../lib/format'
import { Panel } from '../ui/Panel'
import { EmptyState } from '../ui/States'

function List({ items, empty = 'None' }: { items: string[]; empty?: string }) {
  if (items.length === 0) return <p className="text-[13px] text-fg-subtle">{empty}</p>
  return (
    <ul className="list-disc space-y-1 pl-5 text-[13px] text-fg">
      {items.map((item, i) => (
        <li key={i}>{item}</li>
      ))}
    </ul>
  )
}

/** Final report, split into tool-verified facts and model-generated claims. */
export function RunReport({ run }: { run: Run }) {
  const report: FinalReport | null = run.finalReport
  if (!report) {
    return <EmptyState title="No report yet" description={run.error ?? 'The report is produced when the workflow finishes.'} />
  }
  const tests = report.verified.tests
  return (
    <div className="grid gap-4 lg:grid-cols-2">
      <Panel title="Verified by tools" icon={<BadgeCheck className="size-4 text-success" />}>
        <dl className="grid grid-cols-2 gap-3 text-[13px]">
          <div>
            <dt className="text-xs text-fg-subtle">Tests</dt>
            <dd className="font-mono text-fg">
              {tests?.executed ? `${tests.passed}/${tests.total} passed` : `not executed${tests?.unavailable_reason ? `: ${tests.unavailable_reason}` : ''}`}
            </dd>
          </div>
          <div>
            <dt className="text-xs text-fg-subtle">Test runs / debug iterations</dt>
            <dd className="font-mono text-fg">
              {report.verified.test_runs} / {report.verified.debug_iterations}
            </dd>
          </div>
          <div>
            <dt className="text-xs text-fg-subtle">Tool findings</dt>
            <dd className="font-mono text-fg">{report.verified.tool_findings.length}</dd>
          </div>
          <div>
            <dt className="text-xs text-fg-subtle">Files</dt>
            <dd className="font-mono text-fg">{report.verified.files.length}</dd>
          </div>
          <div>
            <dt className="text-xs text-fg-subtle">Duration</dt>
            <dd className="font-mono text-fg">{formatDuration(run.durationSeconds)}</dd>
          </div>
          <div>
            <dt className="text-xs text-fg-subtle">Tokens · est. cost</dt>
            <dd className="font-mono text-fg">
              {(report.usage.input_tokens + report.usage.output_tokens).toLocaleString()} · {formatUsd(report.usage.estimated_cost_usd)}
            </dd>
          </div>
        </dl>
        <div className="mt-4">
          <p className="mb-1 text-xs font-medium text-fg-muted">Known limitations</p>
          <List items={report.limitations} />
        </div>
      </Panel>
      <Panel title="Generated by the model" icon={<Bot className="size-4" />}>
        <p className="mb-3 text-xs text-fg-subtle">
          Written by {report.model.demo ? 'the scripted demo model (not AI)' : report.model.name}. Not independently verified.
        </p>
        {report.generated.summary && <p className="mb-3 text-[13px] text-fg">{report.generated.summary}</p>}
        <p className="mb-1 text-xs font-medium text-fg-muted">Features</p>
        <List items={report.generated.features} />
        <p className="mt-3 mb-1 text-xs font-medium text-fg-muted">Assumptions</p>
        <List items={report.generated.assumptions} />
        {report.tasks_not_verified.length > 0 && (
          <>
            <p className="mt-3 mb-1 text-xs font-medium text-warning">Tasks not verified by a passing test suite</p>
            <List items={report.tasks_not_verified} />
          </>
        )}
      </Panel>
    </div>
  )
}
